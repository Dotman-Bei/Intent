import * as fs from "fs";
import * as path from "path";
import { artifacts } from "hardhat";

/**
 * One source of truth for ABIs: compile here, export to backend/abi (JSON, read by web3.py) and
 * frontend/src/constants/abi (TS consts, so viem keeps its type inference).
 */
const CONTRACTS = [
  "StrategyRegistry",
  "ApprovalGate",
  "IntentVault",
  "MockERC20",
  "MockDEX",
  "MockLendingPool",
];

async function main() {
  const backendDir = path.join(__dirname, "..", "..", "backend", "abi");
  const frontendDir = path.join(__dirname, "..", "..", "frontend", "src", "constants", "abi");
  fs.mkdirSync(backendDir, { recursive: true });
  fs.mkdirSync(frontendDir, { recursive: true });

  const index: string[] = [];

  for (const name of CONTRACTS) {
    const artifact = await artifacts.readArtifact(name);
    fs.writeFileSync(
      path.join(backendDir, `${name}.json`),
      JSON.stringify(artifact.abi, null, 2)
    );
    fs.writeFileSync(
      path.join(frontendDir, `${name}.ts`),
      `// Generated by contracts/scripts/export-abi.ts — do not edit.\n` +
        `export const ${name}ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
    );
    index.push(`export { ${name}ABI } from "./${name}";`);
    console.log(`exported ${name}`);
  }

  fs.writeFileSync(
    path.join(frontendDir, "index.ts"),
    `// Generated by contracts/scripts/export-abi.ts — do not edit.\n${index.join("\n")}\n`
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
